  await pa.click('[data-a="next"]');
  await sleep(900);
  check('끈 B 는 그대로 2쪽', await pb.evaluate(() => document.querySelector('.pv-pg').textContent) === '2 / 3');
  check('끈 B 에 리더 위치 안내', await pb.evaluate(() => /리더 3쪽/.test(document.querySelector('.pv-follow').textContent)), await pb.evaluate(() => document.querySelector('.pv-follow').textContent));
  await pb.click('.pv-follow');
  check('다시 켜면 리더 위치(3쪽)로', await L.waitTrue(pb, () => document.querySelector('.pv-pg').textContent === '3 / 3'));
  await pa.click('[data-a="prev"]'); await pa.click('[data-a="prev"]');
