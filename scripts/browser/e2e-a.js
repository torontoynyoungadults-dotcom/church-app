  await pb.check('.pv-mineonly input');
  check('B 가 "나만 보기"를 체크 → 내 층', await pb.evaluate(() => window.__pv.P.getLayer()) === 'mine');
  const aBefore = await L.teamCount(pa), aPx = await L.overlayPx(pa);
