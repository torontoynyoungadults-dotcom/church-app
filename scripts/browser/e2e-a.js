  check('B 나만 보기 필기가 B 화면에 그려짐', await L.mineCount(pb) === 1);
  await sleep(700);
  check('B 나만 보기 필기는 A 에게 안 보임', await L.overlayPx(pa) === aPx && await L.teamCount(pa) === aBefore);
  await sleep(2200);
  check('B 나만 보기 필기는 서버(HTTP)에 저장', (S.store.mine['FILEID_AAAAAAA1|song|Bob'] || []).length === 1, Object.keys(S.store.mine));

  console.log('· 글자 · 코드 · 기호');
